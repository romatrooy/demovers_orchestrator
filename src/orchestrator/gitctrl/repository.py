class GitRepository:
    def create_worktree(self, base_revision: str) -> str: ...
    def get_head(self, worktree_id: str) -> str: ...
    def get_diff_paths(self, worktree_id: str, base: str, head: str) -> list[str]: ...
    def has_uncommitted_changes(self, worktree_id: str) -> bool: ...
    def commit_all(self, worktree_id: str, message: str) -> str: ...
    def publish(self, worktree_id: str, target_branch: str) -> tuple[str, str]: ...
